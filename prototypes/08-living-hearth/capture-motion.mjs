import {chromium} from '@playwright/test';
import {mkdir,rename,writeFile} from 'node:fs/promises';
const output='handoff/EVIDENCE/living-hearth-2026-10-31';
await mkdir(output+'/video',{recursive:true});
const browser=await chromium.launch({args:['--enable-webgl','--use-angle=swiftshader']});
const context=await browser.newContext({viewport:{width:1280,height:800},recordVideo:{dir:output+'/video',size:{width:1280,height:800}},locale:'zh-CN'});
const page=await context.newPage();
await page.goto('http://127.0.0.1:4342/#discover');
await page.waitForFunction(()=>window.getHearthFlameState?.().textureReady && window.getHearthFlameState().frames>3);
await page.evaluate(()=>document.fonts.ready);
await page.waitForTimeout(1800);
await page.locator('#conversation-input').focus();
await page.locator('#conversation-input').pressSequentially('我想把片段重新拾起来。',{delay:90});
await page.waitForTimeout(600);
await page.locator('#conversation-input').press('Enter');
await page.waitForTimeout(1800);
await page.getByLabel('讨论范围',{exact:true}).selectOption('fragments');
await page.waitForTimeout(1600);
await page.locator('#conversation-input').pressSequentially('当时留下了哪些想法？',{delay:90});
await page.locator('#conversation-input').press('Enter');
await page.waitForTimeout(2200);
const state=await page.evaluate(()=>window.getHearthFlameState());
const video=page.video();await context.close();
await rename(await video.path(),output+'/living-hearth-preview.webm');
await writeFile(output+'/motion-capture.json',JSON.stringify({kind:'actual browser recording',fixtureOnly:true,softwareWebGL:true,finalState:state,scenes:['idle fire','focus and typing','local example send','fire docks','switch project','continue project conversation'],noRealModel:true},null,2)+'\n');
await browser.close();
console.log('Recorded actual prototype motion: living-hearth-preview.webm');
