import { afterEach, beforeEach, expect, it } from 'vitest';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { tmpdir } from 'node:os';
import { ProjectObserver } from '@hearth/project-observer';
import { createGitRepo } from '../../../project-observer/src/testkit/git-fixture.js';
import { AnalysisStore } from '../store/store.js';
import { AnalysisService } from './service.js';
import { MockAnalysisProvider } from '../providers/mock.js';
import { assembleProjectContext } from '../context/assemble.js';
import { redactSecrets } from '../context/redact.js';
let dir:string, observer:ProjectObserver, store:AnalysisStore, service:AnalysisService;
let calls:number;
beforeEach(async()=>{
 dir=await mkdtemp(path.join(tmpdir(),'hearth-r2-'));calls=0;
 observer=new ProjectObserver({dbPath:path.join(dir,'o.sqlite'),watchEnabled:false});store=new AnalysisStore(path.join(dir,'a.sqlite'));
 service=new AnalysisService({observer,store,provider:{id:'pi',model:'synthetic',async analyze(input){calls++;return new MockAnalysisProvider().analyze(input);}}});
});
afterEach(async()=>{service.close();observer.close();await rm(dir,{recursive:true,force:true});});
it('preview is local, stale consent is rejected, exact consent is persisted before provider and feedback survives reads',async()=>{
 const repo=await createGitRepo(dir,'repo',{commit:true,files:{'README.md':'# First\n'}});const p=await observer.registerProject(repo);
 const input={projectId:p.id,trigger:'observe' as const};
 const preview=service.preview(input);expect(calls).toBe(0);
 await expect(service.start(input)).rejects.toMatchObject({code:'CONSENT_REQUIRED'});
 await writeFile(path.join(repo,'README.md'),'# Changed\n');
 await expect(service.start({...input,consentFingerprint:preview.context.contextFingerprint})).rejects.toMatchObject({code:'CONSENT_REQUIRED'});
 expect(calls).toBe(0);
 const next=service.preview(input);const run=await service.start({...input,consentFingerprint:next.context.contextFingerprint});
 expect(calls).toBe(1);expect(store.hasConsent(run.id,run.contextFingerprint,'pi:synthetic')).toBe(true);
 expect(run.stale).toBe(false);service.feedback(run.id,'useful');expect(service.get(run.id)?.feedback).toBe('useful');
 await writeFile(path.join(repo,'README.md'),'# Later\n');expect(service.get(run.id)).toMatchObject({stale:true,staleReason:'context'});
});
it('fingerprint excludes assembly time and file exclusions are enforced before external dispatch',async()=>{
 const repo=await createGitRepo(dir,'repo',{commit:true,files:{'README.md':'API_KEY=synthetic-credential-without-prefix-12345\n','docs/private.md':'internal-secret'}});const p=await observer.registerProject(repo);
 expect(assembleProjectContext(observer,undefined,p.id,'2020-01-01').contextFingerprint).toBe(assembleProjectContext(observer,undefined,p.id,'2026-10-29').contextFingerprint);
 service.setPrivacy(p.id,['README.md','docs/']);
 expect(service.preview({projectId:p.id,trigger:'observe'}).context.files).toEqual([]);
 expect(()=>service.setPrivacy(p.id,['../escape'])).toThrow();
 expect(redactSecrets('API_KEY=synthetic-credential-without-prefix-12345')).not.toContain('synthetic-credential');
 expect(redactSecrets('example abcDEF123ghiJKL456mnoPQR789stuVWX012')).not.toContain('abcDEF123');
});
